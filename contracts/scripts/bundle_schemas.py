"""Bundle schemas/manifest.schema.json + schemas/api.schema.json into one file with all $defs
(build/dso.bundle.schema.json). Code generators read the bundle so TS and Python come from the
same source. Stdlib only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / "schemas/manifest.schema.json").read_text())
api = json.loads((ROOT / "schemas/api.schema.json").read_text())


def rewrite(node):
    if isinstance(node, dict):
        return {k: (v.replace("manifest.schema.json#", "#") if k == "$ref" and isinstance(v, str) else rewrite(v))
                for k, v in node.items()}
    if isinstance(node, list):
        return [rewrite(x) for x in node]
    return node


defs = dict(manifest["$defs"])
defs["Manifest"] = {k: v for k, v in manifest.items() if k not in ("$defs", "$schema", "$id")}
for name, schema in api["$defs"].items():
    if set(schema) == {"$ref"} and schema["$ref"].startswith("manifest.schema.json#/$defs/"):
        continue  # alias to a manifest def that is already present
    defs[name] = schema
bundle = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "title": "DsoContracts",
    "description": "GENERATED by contracts/scripts/bundle_schemas.py. Do not edit; edit schemas/*.json.",
    "type": "object",
    "properties": {name: {"$ref": f"#/$defs/{name}"} for name in defs},
    "$defs": rewrite(defs),
}
out = ROOT / "build/dso.bundle.schema.json"
out.parent.mkdir(exist_ok=True)
out.write_text(json.dumps(bundle, indent=2, ensure_ascii=False) + "\n")
print("wrote", out)
